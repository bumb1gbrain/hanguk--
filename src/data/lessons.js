// บทที่แนะนำตอนนี้: มือใหม่ (ยังไม่ข้ามฮันกึล) ต้องจบบทฮันกึลตามลำดับก่อน แล้วค่อยแนะนำตามช่วงเวลาของวัน
// done = state.lessons (บทที่เคยเรียนจบ), skipHangul = ผู้เล่นบอกว่าอ่านฮันกึลได้แล้ว
export function suggestLesson(date = new Date(), done = {}, skipHangul = false) {
  if (!skipHangul) {
    const next = LESSONS.find((l) => l.group === 'hangul' && !done[l.id])
    if (next) return next
  }
  const hr = date.getHours()
  const hrs = [hr, hr + 24]
  return LESSONS.find((l) => l.group === 'daily' && l.id !== 'greet' && hrs.some((x) => x >= l.hours[0] && x < l.hours[1]))
    || LESSON_BY_ID.night
}
