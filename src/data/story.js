function taleFor(species) {
  const t = TALES[species] || TALES.tiger
  const base = { bg: 'night', show: { avatar: 1, pet: 1 } }
  const out = []
  t.slice(0, 2).forEach(([who, ko, read, th, vocab]) => out.push(L(who, ko, read, th, { ...base, vocab })))
  out.push(L('pet', '{sound}?!', '{soundRead}', '{pet} ตาโต มองเรามาอย่างตั้งใจ แล้วซุกเข้ามาใกล้ๆ', base))
  const [who, ko, read, th, vocab] = t[2]
  out.push(L(who, ko, read, th, { ...base, pose: 'happy', vocab }))
  out.push(L('narr', '이제 말이 조금 통해요. “앉아!”라고 해 볼까요?', 'อีเจ มารี โชกึม ทงเฮโย อันจา ราโก เฮ พลกาโย', 'ตอนนี้พอสื่อสารกันได้นิดหน่อยแล้ว ลองสั่ง “앉아!” (นั่ง) ที่หน้า Home ดูสิ', { ...base, pose: 'happy', vocab: [{ ko: '앉아', th: 'นั่ง' }, { ko: '말', th: 'คำพูด/ภาษา' }] }))
  return out
}

