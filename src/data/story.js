// ช่วงถัดไปที่ควรเล่น: ยังไม่เคยดู + เงื่อนไขครบ + ช่วงก่อนหน้าดูแล้ว
export function pendingPart(s) {
  const seen = s.story?.seen || {}
  return ALL_PARTS.find((p) => !seen[p.id] && (!p.after || seen[p.after]) && p.when(s)) || null
}

